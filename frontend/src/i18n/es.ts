/** Widen leaf strings so `en` can differ while keeping the same key tree. */
type DeepStringify<T> = T extends string
  ? string
  : T extends ReadonlyArray<infer U>
    ? ReadonlyArray<DeepStringify<U>>
    : T extends object
      ? { [K in keyof T]: DeepStringify<T[K]> }
      : T

